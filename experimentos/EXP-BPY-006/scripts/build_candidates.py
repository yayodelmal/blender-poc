"""Build isolated EXP-BPY-006 candidates A (bpy rebuild) and B (Geometry Nodes)."""
import json, os, sys
import bpy, bmesh
from mathutils import Vector

RUN='EXP-BPY-006-20261102T175526Z'
P={'width_mm':80.0,'height_mm':60.0,'base_mm':4.0,'relief_mm':1.0,
   'brick_x_mm':15.0,'brick_y_mm':7.0,'joint_mm':1.2,'pitch_x_mm':16.2,'pitch_y_mm':8.2,'rows':6,'columns_even':5,'columns_odd':4}
OBJ='EXP-BPY-006_ReliefPlate'

def args():
    a=sys.argv[sys.argv.index('--')+1:]
    if len(a)!=2: raise RuntimeError('expected MODE OUTPUT')
    return a

def box(bm, center, size):
    g=bmesh.ops.create_cube(bm,size=2.0)
    for v in g['verts']:
        v.co=Vector(center)+Vector((v.co.x*size[0]/2,v.co.y*size[1]/2,v.co.z*size[2]/2))

def rows():
    out=[]
    y0=-(P['rows']-1)*P['pitch_y_mm']/2
    for r in range(P['rows']):
        n=P['columns_even'] if r%2==0 else P['columns_odd']
        x0=-(n-1)*P['pitch_x_mm']/2
        for c in range(n): out.append((x0+c*P['pitch_x_mm'],y0+r*P['pitch_y_mm']))
    return out

def clear_scene():
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    for m in list(bpy.data.meshes):
        if m.users==0: bpy.data.meshes.remove(m)
    s=bpy.context.scene; s.unit_settings.system='METRIC'; s.unit_settings.scale_length=1.0; s.unit_settings.length_unit='MILLIMETERS'

def make_bpy(output):
    clear_scene(); s=bpy.context.scene
    base_bm=bmesh.new(); box(base_bm,(0,0,P['base_mm']/2000),(P['width_mm']/1000,P['height_mm']/1000,P['base_mm']/1000))
    base_mesh=bpy.data.meshes.new('EXP006_A_Base'); base_bm.to_mesh(base_mesh); base_bm.free()
    obj=bpy.data.objects.new(OBJ,base_mesh); s.collection.objects.link(obj)
    brick_bm=bmesh.new(); ov=0.0002
    for x,y in rows(): box(brick_bm,(x/1000,y/1000,(P['base_mm']+P['relief_mm']/2-ov/2)/1000),(P['brick_x_mm']/1000,P['brick_y_mm']/1000,(P['relief_mm']+ov)/1000))
    brick_mesh=bpy.data.meshes.new('EXP006_A_TemporaryBricks'); brick_bm.to_mesh(brick_mesh); brick_bm.free()
    operands=bpy.data.objects.new('EXP006_A_TemporaryOperands',brick_mesh); s.collection.objects.link(operands)
    bpy.context.view_layer.objects.active=obj; obj.select_set(True); operands.select_set(False)
    boolean=obj.modifiers.new('EXP006_A_ExactUnion','BOOLEAN'); boolean.operation='UNION'; boolean.solver='EXACT'; boolean.object=operands
    if 'FINISHED' not in bpy.ops.object.modifier_apply(modifier=boolean.name): raise RuntimeError('Boolean union failed')
    bpy.data.objects.remove(operands,do_unlink=True); bpy.data.meshes.remove(brick_mesh)
    obj['experiment_id']=RUN; obj['strategy']='A_bpy_parameterized_full_rebuild'; obj['parameters_mm']=json.dumps(P,sort_keys=True); obj['parameter_units']='mm'; obj['brick_count']=len(rows()); obj['editability_note']='Rebuilt from script parameters; not an in-place edit.'
    bpy.context.view_layer.objects.active=obj; obj.select_set(True)
    save(output)
    print('BUILD_A '+json.dumps({'path':output,'parameters':P,'brick_count':len(rows()),'strategy':'full_rebuild'},sort_keys=True))

def gn_node(group,typ,name):
    n=group.nodes.new(typ); n.label=name; return n

def make_gn(output):
    clear_scene(); s=bpy.context.scene
    # Empty carrier object: the evaluated solid is generated by the persisted node group.
    mesh=bpy.data.meshes.new('EXP006_B_GN_CarrierMesh'); obj=bpy.data.objects.new(OBJ,mesh); s.collection.objects.link(obj)
    obj['experiment_id']=RUN; obj['strategy']='B_geometry_nodes'; obj['parameter_units']='mm'; obj['brick_count']=27
    base_bm=bmesh.new(); box(base_bm,(0,0,.002),(.08,.06,.004)); base_mesh=bpy.data.meshes.new('EXP006_B_BooleanBase'); base_bm.to_mesh(base_mesh); base_bm.free()
    helper=bpy.data.objects.new('EXP006_B_ConstructionBase',base_mesh); s.collection.objects.link(helper); helper['role']='boolean_operand'; helper.hide_render=True; helper.hide_set(True)
    obj['construction_base_dimensions_mm']=json.dumps({'width':80.0,'height':60.0,'thickness':4.0},sort_keys=True)
    ng=bpy.data.node_groups.new('EXP-BPY-006_B_ParametricRelief','GeometryNodeTree')
    def sock(name, in_out, socket_type, default=None, minv=None, maxv=None):
        x=ng.interface.new_socket(name=name,in_out=in_out,socket_type=socket_type)
        if default is not None: x.default_value=default
        if minv is not None: x.min_value=minv
        if maxv is not None: x.max_value=maxv
        return x
    inputs={}
    for name,val in [('Relieve (m)',.001),('Ladrillo X (m)',.015),('Ladrillo Y (m)',.007),('Paso X (m)',.0162),('Paso Y (m)',.0082)]: inputs[name]=sock(name,'INPUT','NodeSocketFloat',val,.0001,1.0)
    sock('Geometry','OUTPUT','NodeSocketGeometry')
    n=ng.nodes; l=ng.links
    inp=gn_node(ng,'NodeGroupInput','Parámetros persistentes'); out=gn_node(ng,'NodeGroupOutput','Salida evaluada')
    def mathnode(op,a,b,label):
        n=gn_node(ng,'ShaderNodeMath',label); n.operation=op
        if isinstance(b,(int,float)): n.inputs[1].default_value=b
        else: l.new(b,n.inputs[1])
        l.new(a,n.inputs[0]); return n.outputs[0]
    def combine(x,y,z,label):
        n=gn_node(ng,'ShaderNodeCombineXYZ',label); l.new(x,n.inputs['X']); l.new(y,n.inputs['Y']); l.new(z,n.inputs['Z']); return n.outputs['Vector']
    # Pattern generation uses 5-wide and 4-wide grids, three alternating rows each.
    def grid(countx, county, multx, multy, yoff, label):
        g=gn_node(ng,'GeometryNodeMeshGrid',label); g.inputs['Vertices X'].default_value=countx; g.inputs['Vertices Y'].default_value=county
        sx=mathnode('MULTIPLY',inp.outputs['Paso X (m)'],multx,label+' X span')
        sy=mathnode('MULTIPLY',inp.outputs['Paso Y (m)'],multy,label+' Y span')
        l.new(sx,g.inputs['Size X']); l.new(sy,g.inputs['Size Y'])
        t=gn_node(ng,'GeometryNodeTransform',label+' alternancia'); l.new(g.outputs['Mesh'],t.inputs['Geometry']); t.inputs['Translation'].default_value=(0,yoff,0)
        return t.outputs['Geometry']
    # 3 even rows at y=-20.5,-4.1,12.3 mm and 3 odd rows at -12.3,4.1,20.5 mm.
    ge=grid(5,3,4,2,-.0041,'Filas pares (15 ladrillos)')
    go=grid(4,3,3,2,.0041,'Filas impares (12 ladrillos)')
    j=gn_node(ng,'GeometryNodeJoinGeometry','27 centros'); l.new(ge,j.inputs['Geometry']); l.new(go,j.inputs['Geometry'])
    cube=gn_node(ng,'GeometryNodeMeshCube','Sólido ladrillo con solape')
    brick_z=mathnode('ADD',inp.outputs['Relieve (m)'],.0002,'Relieve + solape')
    brick_size=combine(inp.outputs['Ladrillo X (m)'],inp.outputs['Ladrillo Y (m)'],brick_z,'Dimensiones del ladrillo')
    l.new(brick_size,cube.inputs['Size'])
    inst=gn_node(ng,'GeometryNodeInstanceOnPoints','Distribución'); l.new(j.outputs['Geometry'],inst.inputs['Points']); l.new(cube.outputs['Mesh'],inst.inputs['Instance'])
    realize=gn_node(ng,'GeometryNodeRealizeInstances','Realizar sólidos'); l.new(inst.outputs['Instances'],realize.inputs['Geometry'])
    half_relief=mathnode('MULTIPLY',inp.outputs['Relieve (m)'],.5,'Mitad del relieve')
    lift_z_a=mathnode('ADD',half_relief,.004,'Centro relieve sobre base contractual')
    zero_x=ng.nodes.new('ShaderNodeValue'); zero_x.outputs[0].default_value=0.0
    zero_y=ng.nodes.new('ShaderNodeValue'); zero_y.outputs[0].default_value=0.0
    lift_z=mathnode('SUBTRACT',lift_z_a,.0001,'Centro con solape'); lift_vec=combine(zero_x.outputs[0],zero_y.outputs[0],lift_z,'Traslación Z ladrillos')
    lift=gn_node(ng,'GeometryNodeTransform','Ladrillos sobre base'); l.new(realize.outputs['Geometry'],lift.inputs['Geometry']); l.new(lift_vec,lift.inputs['Translation'])
    l.new(lift.outputs['Geometry'],out.inputs['Geometry'])
    mod=obj.modifiers.new('EXP006_ParametricPattern','NODES'); mod.node_group=ng
    # Store editable values explicitly on the modifier sockets where the interface exposes them.
    for item in ng.interface.items_tree:
        if getattr(item,'in_out',None)=='INPUT' and item.name not in ('Geometry',):
            try: mod[item.identifier]=item.default_value
            except Exception: pass
    fuse=obj.modifiers.new('EXP006_UnionWithBase','BOOLEAN'); fuse.operation='UNION'; fuse.solver='EXACT'; fuse.object=helper
    bpy.context.view_layer.objects.active=obj; obj.select_set(True)
    save(output)
    print('BUILD_B '+json.dumps({'path':output,'group':ng.name,'interfaces':[{'name':i.name,'identifier':i.identifier,'direction':getattr(i,'in_out',None)} for i in ng.interface.items_tree],'strategy':'Geometry Nodes persistent interface'},sort_keys=True))

def save(path):
    os.makedirs(os.path.dirname(path),exist_ok=True)
    if os.path.exists(path): raise FileExistsError(path)
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type=='VIEW_3D':
                area.spaces.active.region_3d.view_location=(0,0,.0025); area.spaces.active.region_3d.view_distance=.2
    r=bpy.ops.wm.save_as_mainfile(filepath=path,check_existing=False)
    if 'FINISHED' not in r: raise RuntimeError('save failed')

mode,path=args()
if mode=='A': make_bpy(path)
elif mode=='B': make_gn(path)
else: raise SystemExit('mode must be A or B')
